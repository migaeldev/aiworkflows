"""Generate Claude Code slash-command adapters from the harness command table.

The "Slash Commands & Aliases" table in aiworkspace/README.md is the single
source of truth. For every primary command and alias it lists, this writes a
thin .claude/skills/<name>/SKILL.md that tells Claude to follow the canonical
skill under aiworkspace/skills/. Re-run after editing the table.

Usage:
    python tools/gen_claude_adapters.py          # write/update adapters
    python tools/gen_claude_adapters.py --check  # exit 1 if adapters are out of date
"""

import argparse
import json
import re
import shutil
import sys
from dataclasses import dataclass, field
from pathlib import Path

MARKER = "<!-- Generated by tools/gen_claude_adapters.py from aiworkspace/README.md. Do not edit by hand. -->"
TABLE_HEADING = "Slash Commands & Aliases"

# Steps that only a human may start (AGENTS.md Directive #7): Claude must not auto-invoke them.
HUMAN_ONLY = {"finalize", "promote"}

ARGUMENT_HINTS = {
    "map": "[paths to limit the map to]",
    "brand": "[what to change]",
    "persona": "[project | <workspace>] [what to change]",
    "define": "[workspace-name] [what it's for]",
    "plan": "[workspace] <feature, change, or ask>",
    "resources": "[workspace/feature]",
    "process": "[workspace/feature] [task]",
    "finalize": "[workspace/feature]",
    "promote": "[workspace]",
}


@dataclass
class Command:
    stage: str
    primary: str
    aliases: list = field(default_factory=list)
    target: str = ""  # canonical SKILL.md path, relative to the repo root


def parse_commands(readme: str) -> list:
    """Parse the slash-command table out of aiworkspace/README.md."""
    start = readme.find(TABLE_HEADING)
    if start == -1:
        raise ValueError(f"'{TABLE_HEADING}' table not found")
    commands = []
    for line in readme[start:].splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 4 or not cells[1].startswith("`/"):
            if commands and not line.strip():
                break  # blank line after the table ends it
            continue
        stage, primary, aliases, target = cells
        link = re.search(r"\]\(\./([^)]+)\)", target)
        if not link:
            raise ValueError(f"no skill link for {primary}")
        commands.append(Command(
            stage=stage,
            primary=primary.strip("`/"),
            aliases=re.findall(r"`/([^`]+)`", aliases),
            target=f"aiworkspace/{link.group(1)}",
        ))
    if not commands:
        raise ValueError(f"'{TABLE_HEADING}' table has no commands")
    return commands


def read_description(skill_md: Path) -> str:
    """Return the one-line `description:` from a skill's frontmatter."""
    text = skill_md.read_text(encoding="utf-8")
    head = text.split("---", 2)[1] if text.startswith("---") else ""
    for line in head.splitlines():
        if line.startswith("description:"):
            return line.partition(":")[2].strip()
    raise ValueError(f"{skill_md} has no description")


def _yaml_value(key: str, value) -> str:
    if isinstance(value, bool):
        return str(value).lower()
    if key == "name":
        return value  # command names are plain kebab-case words
    # JSON strings are valid YAML double-quoted scalars, so colons/quotes in descriptions stay safe.
    return json.dumps(value, ensure_ascii=False)


def _frontmatter(fields: dict) -> str:
    lines = [f"{key}: {_yaml_value(key, value)}" for key, value in fields.items()]
    return "---\n" + "\n".join(lines) + "\n---\n"


def _body(command: Command, invoked_as: str) -> str:
    gate = (
        f"\nThis step is human-only. Run it only because the user typed `/{invoked_as}`, "
        "and still confirm before moving or writing anything (AGENTS.md Directive #7).\n"
        if command.primary in HUMAN_ONLY else ""
    )
    return (
        f"\n{MARKER}\n\n"
        f"# /{invoked_as} ({command.stage})\n\n"
        f"Claude Code adapter for the harness skill `{command.target}`. That file is the source of truth; "
        "this one only exposes it as a slash command.\n"
        f"{gate}\n"
        f"1. Read `{command.target}` in full and follow it exactly.\n"
        "2. Treat this as the user's input to the skill (it may be empty): $ARGUMENTS\n"
        "3. `AGENTS.md` applies throughout, especially the immutability guardrail (Directive #6) "
        "and the step gate (Directive #7).\n"
    )


def render_primary(command: Command, description: str) -> str:
    fields = {"name": command.primary, "description": description}
    if command.primary in ARGUMENT_HINTS:
        fields["argument-hint"] = ARGUMENT_HINTS[command.primary]
    if command.primary in HUMAN_ONLY:
        fields["disable-model-invocation"] = True
    return _frontmatter(fields) + _body(command, command.primary)


def render_alias(alias: str, command: Command) -> str:
    fields = {"name": alias, "description": f"Alias of /{command.primary} ({command.stage})."}
    if command.primary in ARGUMENT_HINTS:
        fields["argument-hint"] = ARGUMENT_HINTS[command.primary]
    fields["disable-model-invocation"] = True  # only the primary is auto-discoverable
    return _frontmatter(fields) + _body(command, alias)


def build(root: Path) -> dict:
    """Map each adapter path (relative to root) to its expected content."""
    commands = parse_commands((root / "aiworkspace" / "README.md").read_text(encoding="utf-8"))
    files = {}
    for command in commands:
        description = read_description(root / command.target)
        files[f".claude/skills/{command.primary}/SKILL.md"] = render_primary(command, description)
        for alias in command.aliases:
            files[f".claude/skills/{alias}/SKILL.md"] = render_alias(alias, command)
    return files


def sync(root: Path, check: bool) -> list:
    """Write adapters (or, with check, only report). Returns paths that are/were out of date."""
    expected = build(root)
    drift = []
    for rel, content in expected.items():
        path = root / rel
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            drift.append(rel)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")

    # Remove adapters this script generated earlier that are no longer in the table.
    # Hand-written skills (no MARKER) are never touched.
    skills_dir = root / ".claude" / "skills"
    if skills_dir.is_dir():
        for skill_md in sorted(skills_dir.glob("*/SKILL.md")):
            rel = skill_md.relative_to(root).as_posix()
            if rel not in expected and MARKER in skill_md.read_text(encoding="utf-8"):
                drift.append(rel)
                if not check:
                    shutil.rmtree(skill_md.parent)
    return drift


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report out-of-date adapters without writing")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    args = parser.parse_args()

    drift = sync(args.root, check=args.check)
    if args.check:
        for rel in drift:
            print(f"out of date: {rel}")
        return 1 if drift else 0
    print(f"updated {len(drift)} adapter(s)" if drift else "adapters already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
